/**
 * `recall`, and the archive it reads.
 *
 * The cases that matter are the ones where the archive and the live transcript
 * disagree — because that is the whole reason the archive exists, and it is the
 * state every test written against a fresh conversation would miss.
 */

import { beforeEach, describe, expect, it } from "vitest";
import type { CoreMessage } from "../core/client";
import {
  ARCHIVE_MAX_CHARS,
  ARCHIVE_TOOL_EXCERPT_CHARS,
  appendArchive,
  boundArchive,
  entriesFor,
  readArchive,
  type ArchiveEntry,
} from "../sessions/archive";
import { saveSession } from "../sessions/store";
import { executeRecall } from "./recall";

let storage: Map<string, unknown>;

beforeEach(() => {
  storage = new Map();
  const area = {
    async get(key?: string | null) {
      return typeof key === "string" && storage.has(key)
        ? { [key]: storage.get(key) }
        : {};
    },
    async set(items: Record<string, unknown>) {
      for (const [k, v] of Object.entries(items)) storage.set(k, v);
    },
    async remove(keys: string | string[]) {
      for (const k of Array.isArray(keys) ? keys : [keys]) storage.delete(k);
    },
    async clear() {
      storage.clear();
    },
  };
  (globalThis as Record<string, unknown>).chrome = {
    storage: { local: area, sync: area },
  };
});

const turn = (question: string, answer: string): CoreMessage[] => [
  { role: "user", content: question },
  { role: "assistant", content: answer },
];

describe("what the archive keeps", () => {
  it("keeps what people said in full", async () => {
    // The irreplaceable half. A person's own words cannot be regenerated by any
    // means, and they are small — a long question is a few hundred bytes
    // against a page read of forty kilobytes.
    const said = "q".repeat(9_000);
    const entries = entriesFor([{ role: "user", content: said }]);
    expect(entries[0].text).toBe(said);
    expect(entries[0].clipped).toBeUndefined();
  });

  it("keeps a tool result as an excerpt, and says so", async () => {
    const entries = entriesFor([
      {
        role: "assistant",
        content: null,
        tool_calls: [
          {
            id: "c1",
            type: "function",
            function: { name: "read_page", arguments: "{}" },
          },
        ],
      },
      { role: "tool", tool_call_id: "c1", content: "p".repeat(50_000) },
    ]);
    const result = entries.find((e) => e.role === "tool");
    expect(result?.text).toHaveLength(ARCHIVE_TOOL_EXCERPT_CHARS);
    expect(result?.clipped).toBe(true);
    // Named by the tool that produced it, not by its call id — the difference
    // between a hit a model can use and one it has to guess at.
    expect(result?.tool).toBe("read_page");
  });

  it("spends tool excerpts before anything anyone said", async () => {
    // The ordering is the whole judgement: what can be fetched again goes first.
    const entries: ArchiveEntry[] = [
      { role: "user", text: "the irreplaceable question", at: 1 },
      { role: "tool", text: "p".repeat(ARCHIVE_MAX_CHARS), at: 2, tool: "read_page" },
      { role: "assistant", text: "the irreplaceable answer", at: 3 },
    ];
    const bounded = boundArchive(entries);
    expect(bounded.map((e) => e.text)).toContain("the irreplaceable question");
    expect(bounded.map((e) => e.text)).toContain("the irreplaceable answer");
    expect(bounded.find((e) => e.role === "tool")?.text).toMatch(
      /no longer kept/,
    );
  });

  it("survives compaction, because compaction never touches it", async () => {
    // THE POINT OF THE WHOLE MODULE. Compaction rewrites the live transcript in
    // place; if the archive were the same copy, the recovery hint on every
    // summary would be false the moment the first summary was written.
    await appendArchive("s1", turn("what does the pricing page say?", "It says $19 a month."));
    // Whatever happens to the live transcript afterwards…
    await saveSession("s1", [{ role: "user", content: "[COMPACTION MARKER] gen=1\nsummary\n[END COMPACTION]" }]);
    const entries = await readArchive("s1");
    expect(entries.map((e) => e.text)).toContain("It says $19 a month.");
  });
});

describe("search", () => {
  beforeEach(async () => {
    await appendArchive("s1", turn("how much is Pro?", "Pro is $19 a month."));
    await appendArchive("s1", turn("and the allowance?", "The allowance is $19."));
  });

  it("finds a phrase and addresses it as a place", async () => {
    const out = await executeRecall(
      { query: "$19 a month" },
      { currentSessionId: "s1", currentTitle: "Pricing" },
    );
    expect(out).toContain("$19 a month");
    // `conversation · turn N · role` — an address the model can read back with
    // mode:"read".
    expect(out).toMatch(/Pricing · turn \d+ · assistant/);
  });

  it("searches only this conversation unless told otherwise", async () => {
    // A recall tool whose fallback is every conversation is a recall tool that
    // leaks between them. The desktop's original shipped with exactly that
    // inversion, because its "current session" parameter was never injected.
    await saveSession("s2", [{ role: "user", content: "x" }], { title: "Other" });
    await appendArchive("s2", turn("secret", "the other conversation's answer"));

    const scoped = await executeRecall(
      { query: "other conversation" },
      { currentSessionId: "s1", currentTitle: "Pricing" },
    );
    expect(scoped).toMatch(/No match/);

    const wide = await executeRecall(
      { query: "other conversation", conversation: "all" },
      { currentSessionId: "s1", currentTitle: "Pricing" },
    );
    expect(wide).toContain("the other conversation's answer");
  });

  it("finds an earlier conversation by part of its title", async () => {
    await saveSession("s2", [{ role: "user", content: "x" }], {
      title: "Kettle research",
    });
    await appendArchive("s2", turn("which kettle?", "The Bosch one, 3kW."));
    const out = await executeRecall(
      { query: "Bosch", conversation: "kettle" },
      { currentSessionId: "s1" },
    );
    expect(out).toContain("The Bosch one");
  });

  it("says what to do when a title matches nothing", async () => {
    const out = await executeRecall(
      { query: "x", conversation: "nonexistent" },
      { currentSessionId: "s1" },
    );
    expect(out).toContain("nonexistent");
    expect(out).toContain('conversation:"all"');
  });

  it("explains a miss rather than just reporting one", async () => {
    // A bare "no results" leaves the model to conclude the detail never
    // existed. The excerpt rule is why a page's contents may genuinely not be
    // findable, and knowing that is what sends it to read the page again.
    const out = await executeRecall(
      { query: "something never said" },
      { currentSessionId: "s1", currentTitle: "Pricing" },
    );
    expect(out).toMatch(/No match/);
    expect(out).toMatch(/excerpt/i);
  });

  it("asks for a query rather than returning the whole conversation", async () => {
    const out = await executeRecall({}, { currentSessionId: "s1" });
    expect(out).toMatch(/needs a query/i);
  });

  it("bounds what it returns, because this runs right after compaction", async () => {
    // A search that returned whole page reads would undo the work that made the
    // call necessary.
    for (let i = 0; i < 200; i++) {
      await appendArchive("s3", turn(`needle ${i}`, `needle answer ${i}`));
    }
    const out = await executeRecall(
      { query: "needle", limit: 1_000 },
      { currentSessionId: "s3", currentTitle: "Long" },
    );
    expect(out.length).toBeLessThan(20_000);
    expect(out).toMatch(/showing \d+/);
  });
});

describe("read", () => {
  it("returns consecutive turns and says how to get the next page", async () => {
    for (let i = 0; i < 30; i++) {
      await appendArchive("s1", turn(`question ${i}`, `answer ${i}`));
    }
    const out = await executeRecall(
      { mode: "read", limit: 4 },
      { currentSessionId: "s1", currentTitle: "Long" },
    );
    expect(out).toContain("question 0");
    expect(out).toContain("offset 4");
  });

  it("numbers turns the same way search does", async () => {
    // THE INVARIANT THAT MAKES THE TWO MODES ONE TOOL. `search` reports a turn
    // number and `read` pages by offset; if they disagreed, reading around a
    // hit would land in the wrong place.
    await appendArchive("s1", turn("alpha", "first answer"));
    await appendArchive("s1", turn("bravo", "second answer"));

    const found = await executeRecall(
      { query: "second answer" },
      { currentSessionId: "s1", currentTitle: "T" },
    );
    const turnNumber = Number(/turn (\d+)/.exec(found)?.[1]);
    const read = await executeRecall(
      { mode: "read", offset: turnNumber - 1, limit: 1 },
      { currentSessionId: "s1", currentTitle: "T" },
    );
    expect(read).toContain("second answer");
  });

  it("says how far the conversation goes when asked past its end", async () => {
    await appendArchive("s1", turn("only", "one"));
    const out = await executeRecall(
      { mode: "read", offset: 500 },
      { currentSessionId: "s1", currentTitle: "T" },
    );
    expect(out).toContain("500");
    expect(out).toContain("2");
  });

  it("is honest about an empty archive rather than silent", async () => {
    const out = await executeRecall(
      { mode: "read" },
      { currentSessionId: "never-used", currentTitle: "Fresh" },
    );
    expect(out).toMatch(/Nothing is recorded/);
  });
});
