/**
 * What was actually said, kept apart from what the model is currently sent.
 *
 * WHY THIS EXISTS AT ALL. Compaction rewrites the live transcript in place —
 * that is the point of it, and it is what stops every round re-paying to clip
 * the same history. But it also means the live transcript is no longer a record
 * of the conversation, and `recall`'s whole promise ("the detail behind this
 * summary is not lost") would be false the moment the first summary was written.
 * The desktop has this for free: `session_messages` feeds the UI's scrollback
 * and the compactor never touches it. Here there was one copy, so there now
 * needs to be two.
 *
 * APPEND-ONLY, AND COMPACTION NEVER TOUCHES IT. Each turn's new messages are
 * appended as they happen. Nothing rewrites an entry once written, so an archive
 * cannot be compacted by accident.
 *
 * WHAT IT KEEPS IN FULL, AND WHAT IT DOES NOT.
 *
 *   User and assistant text — IN FULL, always. This is the irreplaceable half of
 *   a conversation. A person's own words cannot be regenerated by any means, and
 *   they are small: a long question is a few hundred bytes against a page read of
 *   forty kilobytes.
 *
 *   Tool results — AN EXCERPT. They are the bulk by two orders of magnitude and
 *   they are regenerable: the page can be read again. Storing them whole would
 *   put a handful of research sessions into Chrome's storage quota and buy back
 *   something the agent can fetch. The excerpt is enough for `recall` to answer
 *   "did that page mention a price" and not enough to reason from, which is the
 *   honest shape of the promise.
 *
 * That split is the same rule as the egress rule for cross-device sync, one
 * layer down, and for the same reason.
 */

import type { CoreMessage } from "../core/client";
import { api } from "../shared/browser-api";

const archiveKey = (id: string) => `atlarix.archive.${id}.v1`;

/** How much of a tool result is kept. Enough to search, not enough to reason from. */
export const ARCHIVE_TOOL_EXCERPT_CHARS = 1_500;

/**
 * The per-conversation archive ceiling, in characters.
 *
 * `chrome.storage.local` is roughly 10 MB across everything the extension
 * stores, shared with twenty conversations and their live transcripts. 200 KB
 * per conversation leaves that comfortable, and a conversation reaches it only
 * after dozens of page reads.
 */
export const ARCHIVE_MAX_CHARS = 200_000;

export interface ArchiveEntry {
  role: "user" | "assistant" | "tool";
  /** The text as said, or the excerpt for a tool result. */
  text: string;
  at: number;
  /** The tool that produced a `tool` row, so a hit reads as something. */
  tool?: string;
  /** True when `text` is not the whole of what was there. */
  clipped?: boolean;
}

function isEntry(value: unknown): value is ArchiveEntry {
  if (typeof value !== "object" || value === null) return false;
  const e = value as Record<string, unknown>;
  return (
    (e.role === "user" || e.role === "assistant" || e.role === "tool") &&
    typeof e.text === "string" &&
    typeof e.at === "number"
  );
}

/**
 * Turn a turn's messages into archive entries.
 *
 * A tool result is matched back to the call that produced it so the entry can
 * say `read_page` rather than `call_3`, which is the difference between a hit a
 * model can use and one it has to guess at.
 */
export function entriesFor(messages: CoreMessage[]): ArchiveEntry[] {
  const at = Date.now();
  const names = new Map<string, string>();
  for (const m of messages) {
    if (m.role !== "assistant") continue;
    for (const c of m.tool_calls ?? []) names.set(c.id, c.function.name);
  }

  const out: ArchiveEntry[] = [];
  for (const m of messages) {
    if (m.role === "user") {
      if (m.content.trim()) out.push({ role: "user", text: m.content, at });
    } else if (m.role === "assistant") {
      if (m.content?.trim())
        out.push({ role: "assistant", text: m.content, at });
    } else if (m.role === "tool") {
      const clipped = m.content.length > ARCHIVE_TOOL_EXCERPT_CHARS;
      out.push({
        role: "tool",
        text: clipped
          ? m.content.slice(0, ARCHIVE_TOOL_EXCERPT_CHARS)
          : m.content,
        at,
        tool: names.get(m.tool_call_id) ?? "tool",
        ...(clipped ? { clipped: true } : {}),
      });
    }
  }
  return out;
}

/**
 * Bring an archive back under its ceiling.
 *
 * TOOL EXCERPTS GO FIRST, OLDEST FIRST, and only then whole entries. The order
 * is the same judgement the whole file rests on: what can be fetched again is
 * spent before what cannot. Dropping the user's oldest question to keep the
 * oldest page read would be exactly backwards.
 */
export function boundArchive(entries: ArchiveEntry[]): ArchiveEntry[] {
  const size = (list: ArchiveEntry[]) =>
    list.reduce((n, e) => n + e.text.length, 0);
  if (size(entries) <= ARCHIVE_MAX_CHARS) return entries;

  const out = [...entries];
  for (let i = 0; i < out.length && size(out) > ARCHIVE_MAX_CHARS; i++) {
    const e = out[i];
    if (e.role !== "tool" || e.text.startsWith("[")) continue;
    out[i] = {
      ...e,
      text: `[${e.tool ?? "tool"} result no longer kept — read the page again if you need it]`,
      clipped: true,
    };
  }
  // Still over: the conversation is genuinely enormous in what people said.
  // Drop from the front, which is the only part a summary has already covered.
  let start = 0;
  while (start < out.length - 1 && size(out.slice(start)) > ARCHIVE_MAX_CHARS) {
    start += 1;
  }
  return out.slice(start);
}

/** Everything recorded for a conversation, oldest first. Never throws. */
export async function readArchive(
  sessionId: string,
): Promise<ArchiveEntry[]> {
  try {
    const key = archiveKey(sessionId);
    const bag = await api().storage.local.get<Record<string, unknown>>(key);
    const raw = bag?.[key];
    return Array.isArray(raw) ? raw.filter(isEntry) : [];
  } catch {
    return [];
  }
}

/**
 * Record this turn's new messages.
 *
 * FAILS SILENTLY. An archive that could not be written is a `recall` that finds
 * less later; it is not a reason to interrupt a turn that is otherwise working,
 * and the live conversation on screen is unaffected.
 */
export async function appendArchive(
  sessionId: string,
  messages: CoreMessage[],
): Promise<void> {
  const fresh = entriesFor(messages);
  if (fresh.length === 0) return;
  try {
    const existing = await readArchive(sessionId);
    await api().storage.local.set({
      [archiveKey(sessionId)]: boundArchive([...existing, ...fresh]),
    });
  } catch {
    // See above.
  }
}

export async function deleteArchive(sessionId: string): Promise<void> {
  try {
    await api().storage.local.remove(archiveKey(sessionId));
  } catch {
    // Nothing to do; an orphan archive is bounded and will be overwritten.
  }
}

export async function deleteArchives(sessionIds: string[]): Promise<void> {
  if (sessionIds.length === 0) return;
  try {
    await api().storage.local.remove(sessionIds.map(archiveKey));
  } catch {
    // As above.
  }
}
