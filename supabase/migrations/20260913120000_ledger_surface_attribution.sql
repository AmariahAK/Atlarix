-- ---------------------------------------------------------------------------
-- Surface attribution on the ledger: 'cli' and 'extension' join 'app' and
-- 'reviewer', and the USER path finally gets a label.
-- ---------------------------------------------------------------------------
--
-- WHY NOW, AND NOT WHEN THE SURFACES SHIP. A ledger row cannot be re-attributed
-- later. Spend recorded without a source is indistinguishable from app spend
-- forever, so the first month of CLI and extension usage would be permanently
-- unsplittable. This is cheap today and impossible retroactively.
--
-- 'app' STAYS THE DESKTOP'S VALUE. Renaming it to 'desktop' would split one
-- product across two rows on the account page and need a backfill of every
-- historical row, for no gain — the only thing missing was the ABILITY to say
-- something other than 'app' on the user path.
--
-- WHAT NEEDED NO CHANGE, checked rather than assumed:
--   * `credit_transactions.source` and `.repo` already exist (20260825120000).
--   * `debit_wallet_service` already takes `p_source` — only its allowlist is
--     widened below.
--   * `get_credit_breakdown` (20260827160000) does `GROUP BY COALESCE(source,
--     'app')` with no hardcoded list, so four sources render as four rows with
--     no SQL change at all.
--
-- THE ALLOWLIST LIVES IN TWO PLACES ON PURPOSE — the CHECK constraint and the
-- `IF ... NOT IN` guards. The constraint is the one that cannot be bypassed;
-- the guards exist so a bad value returns `invalid_source` rather than raising,
-- which is what the proxy's error handling expects.

BEGIN;

-- ---------------------------------------------------------------------------
-- 1. Widen the CHECK.
-- ---------------------------------------------------------------------------
-- The constraint was created inline by `ADD COLUMN ... CHECK (...)`, so its
-- name was GENERATED by Postgres and is not written down anywhere. Look it up
-- rather than guessing `credit_transactions_source_check`: a hardcoded DROP
-- that misses fails the whole migration, and one that matches the wrong
-- constraint silently removes a different rule.
DO $$
DECLARE
  constraint_name text;
BEGIN
  SELECT con.conname INTO constraint_name
    FROM pg_constraint con
    JOIN pg_class rel ON rel.oid = con.conrelid
    JOIN pg_namespace nsp ON nsp.oid = rel.relnamespace
   WHERE nsp.nspname = 'public'
     AND rel.relname = 'credit_transactions'
     AND con.contype = 'c'
     AND pg_get_constraintdef(con.oid) ILIKE '%source%'
   LIMIT 1;

  IF constraint_name IS NOT NULL THEN
    EXECUTE format(
      'ALTER TABLE public.credit_transactions DROP CONSTRAINT %I',
      constraint_name
    );
  END IF;
END;
$$;

ALTER TABLE public.credit_transactions
  ADD CONSTRAINT credit_transactions_source_check
  CHECK (source IN ('app', 'reviewer', 'cli', 'extension'));

COMMENT ON COLUMN public.credit_transactions.source IS
  'Which Atlarix surface spent this: app (desktop), reviewer, cli, extension. '
  'Set server-side from a validated header — never from a client string.';

-- ---------------------------------------------------------------------------
-- 2. debit_wallet gains p_source.
-- ---------------------------------------------------------------------------
-- CREATE OR REPLACE CANNOT DO THIS. Adding a parameter changes the signature,
-- so Postgres creates an OVERLOAD rather than replacing — and then a two-arg
-- call is ambiguous against the three-arg-with-default version ("function
-- is not unique"). The old one has to go.
DROP FUNCTION IF EXISTS public.debit_wallet(text, bigint);

CREATE FUNCTION public.debit_wallet(
  p_generation_id text,
  p_cents bigint,
  p_source text DEFAULT 'app'
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  uid uuid := auth.uid();
  bal bigint;
BEGIN
  IF uid IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'error', 'not_authenticated');
  END IF;
  IF p_cents IS NULL OR p_cents <= 0 THEN
    RETURN jsonb_build_object('ok', false, 'error', 'invalid_amount');
  END IF;
  IF p_generation_id IS NULL OR length(trim(p_generation_id)) = 0 THEN
    RETURN jsonb_build_object('ok', false, 'error', 'missing_generation_id');
  END IF;
  -- 'reviewer' is deliberately NOT accepted here. That path is service-token
  -- only, and letting a user-JWT call claim it would put reviewer spend on the
  -- account page for work no installation did.
  IF p_source IS NULL OR p_source NOT IN ('app', 'cli', 'extension') THEN
    RETURN jsonb_build_object('ok', false, 'error', 'invalid_source');
  END IF;

  INSERT INTO credit_wallet (user_id) VALUES (uid) ON CONFLICT (user_id) DO NOTHING;

  INSERT INTO credit_transactions (user_id, delta_cents, kind, ref, source)
  VALUES (uid, -p_cents, 'debit', p_generation_id, p_source)
  ON CONFLICT (kind, ref) DO NOTHING;
  IF NOT FOUND THEN
    -- Already charged for this generation — no-op. Unchanged from the original:
    -- the (kind, ref) unique index is the idempotency key, and a repeat must
    -- not double-charge no matter which surface sent it.
    RETURN jsonb_build_object(
      'ok', true, 'balance_cents', wallet_spendable(uid), 'duplicate', true
    );
  END IF;

  -- Every user-path surface draws the Pro allowance first. Only 'reviewer'
  -- prefers a different one, and it cannot reach this function.
  bal := spend_from_wallet(uid, p_cents, 'pro');
  RETURN jsonb_build_object('ok', true, 'balance_cents', bal);
END;
$$;

-- ---------------------------------------------------------------------------
-- 3. Widen the service path's guard to match the constraint.
-- ---------------------------------------------------------------------------
-- Signature unchanged, so CREATE OR REPLACE is correct here.
CREATE OR REPLACE FUNCTION public.debit_wallet_service(
  p_user_id uuid,
  p_generation_id text,
  p_cents bigint,
  p_source text DEFAULT 'reviewer',
  p_repo text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  bal bigint;
BEGIN
  IF COALESCE(auth.role(), '') <> 'service_role' THEN
    RETURN jsonb_build_object('ok', false, 'error', 'forbidden');
  END IF;
  IF p_user_id IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'error', 'missing_user');
  END IF;
  IF p_cents IS NULL OR p_cents <= 0 THEN
    RETURN jsonb_build_object('ok', false, 'error', 'invalid_amount');
  END IF;
  IF p_generation_id IS NULL OR length(trim(p_generation_id)) = 0 THEN
    RETURN jsonb_build_object('ok', false, 'error', 'missing_generation_id');
  END IF;
  IF p_source NOT IN ('app', 'reviewer', 'cli', 'extension') THEN
    RETURN jsonb_build_object('ok', false, 'error', 'invalid_source');
  END IF;

  INSERT INTO credit_wallet (user_id) VALUES (p_user_id) ON CONFLICT (user_id) DO NOTHING;

  INSERT INTO credit_transactions (user_id, delta_cents, kind, ref, source, repo)
  VALUES (p_user_id, -p_cents, 'debit', p_generation_id, p_source, p_repo)
  ON CONFLICT (kind, ref) DO NOTHING;
  IF NOT FOUND THEN
    RETURN jsonb_build_object(
      'ok', true, 'balance_cents', wallet_spendable(p_user_id), 'duplicate', true
    );
  END IF;

  bal := spend_from_wallet(
    p_user_id, p_cents, CASE WHEN p_source = 'reviewer' THEN 'reviewer' ELSE 'pro' END
  );
  RETURN jsonb_build_object('ok', true, 'balance_cents', bal);
END;
$$;

-- ---------------------------------------------------------------------------
-- 4. Re-issue the grants — for the new signature, and because REPLACE undoes them.
-- ---------------------------------------------------------------------------
-- TWO SEPARATE REASONS, and both are traps this project has already paid for:
--
--   * `debit_wallet` has a NEW signature, so the grants pinned to
--     `debit_wallet(text, bigint)` in 20260826130000 no longer apply to
--     anything. Without this the function would be unreachable by
--     `authenticated`, and every Core turn would fail at the debit.
--   * `CREATE OR REPLACE` RE-GRANTS EXECUTE TO PUBLIC. That is recorded from
--     the 2026-07 Supabase remediation: the replace silently restores the
--     default ACL, so `debit_wallet_service` would become callable by anon
--     even though nothing in this file says so.
--
-- VERIFY BY READING `proacl` BACK after applying. The CLI reporting "up to
-- date" proves only that it ran the file, not what the ACL now says:
--
--   SELECT p.proname, p.proacl FROM pg_proc p
--     JOIN pg_namespace n ON n.oid = p.pronamespace
--    WHERE n.nspname = 'public'
--      AND p.proname IN ('debit_wallet', 'debit_wallet_service');
--
-- Neither should list `=X/` (PUBLIC).
REVOKE EXECUTE ON FUNCTION public.debit_wallet(text, bigint, text) FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION public.debit_wallet(text, bigint, text) FROM anon;
GRANT EXECUTE ON FUNCTION public.debit_wallet(text, bigint, text) TO authenticated;

REVOKE EXECUTE ON FUNCTION public.debit_wallet_service(uuid, text, bigint, text, text) FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION public.debit_wallet_service(uuid, text, bigint, text, text) FROM authenticated, anon;
GRANT EXECUTE ON FUNCTION public.debit_wallet_service(uuid, text, bigint, text, text) TO service_role;

COMMIT;
