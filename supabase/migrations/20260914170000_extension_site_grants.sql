-- ---------------------------------------------------------------------------
-- Site grants, visible on the website and revocable from it.
-- ---------------------------------------------------------------------------
--
-- WHAT THIS DOES NOT CHANGE. `site-grants.ts` says a grant lives in
-- `storage.sync` and not in an account, because a grant is a statement about
-- ONE BROWSER PROFILE -- "in this browser, the agent may act on
-- app.example.com" -- and pushing it to every device the user signs into would
-- widen the agent's reach on machines they never approved it on. That reasoning
-- still holds and this table does not touch it: the BROWSER remains the only
-- place a grant is created, and nothing here can create one.
--
-- WHAT IT ADDS IS A MIRROR AND A ONE-WAY VALVE. The extension publishes the
-- list it already shows in its own drawer, and the website can mark a row
-- revoked. Every flow through this table NARROWS what the agent may touch;
-- there is no path that widens it. That asymmetry is the whole safety argument,
-- and it is why `origin` arrives from the extension and is never accepted as a
-- new row from the web.
--
-- WHY A DEVICE COLUMN. Without one, a work laptop's grants and a home
-- machine's merge into a single list, and "Revoke" on a site the user is
-- looking at would silently hit a browser they are not sitting at. Revoking too
-- much is safe but it is not HONEST, and the list would be describing a state
-- no single browser is in. `device_id` is an opaque client-generated value in
-- `storage.local` -- local, not sync, because it identifies the profile rather
-- than the account.
--
-- THE COST, STATED. This publishes which sites the user has let the agent act
-- on, to their own account. That is real metadata: a row here says the user has
-- an account at that origin. It is the price of being able to see and revoke
-- them anywhere, it is the user's own data under RLS, and it is narrower than
-- the conversation transcripts this account already syncs.
--
-- REVOCATION IS NOT INSTANT AND THE UI MUST NOT CLAIM IT IS. A website cannot
-- reach into Chrome: `permissions.remove()` runs in the extension. So the web
-- sets `revoked_at`, and the extension applies it the next time the panel
-- opens -- `permissions.remove()` first, then `revokeSite()`, the same order
-- `revokeHostAccess()` already uses, because a record without the permission is
-- a grant that silently does not work.

BEGIN;

CREATE TABLE IF NOT EXISTS public.extension_site_grants (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,

  -- Opaque, generated by the extension. Never rendered raw.
  device_id text NOT NULL,
  -- What the user sees: "Chrome on macOS". Cosmetic, and replaced on every
  -- push, so a browser that changes platform strings just re-labels itself.
  device_label text NOT NULL DEFAULT '',

  -- Serialized origin, exactly as `originOf()` produced it: scheme + host +
  -- non-default port. Punycode for an IDN, which is the point -- the Cyrillic
  -- and Latin spellings of a name are different origins and must render as
  -- different rows.
  origin text NOT NULL,

  granted_at timestamptz NOT NULL DEFAULT now(),
  -- Set by the WEBSITE only. Non-null means "the extension has not applied this
  -- yet"; once it has, the row is gone.
  revoked_at timestamptz,
  last_seen_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),

  -- Only http(s) can hold a grant, and `originOf` already refuses everything
  -- else. Restated here because this column is what the website renders and a
  -- `javascript:` string in a list of links is a hole with a long history.
  CONSTRAINT extension_site_grants_origin_shape
    CHECK (origin ~ '^https?://[A-Za-z0-9._~-]+(:[0-9]{1,5})?$'),
  CONSTRAINT extension_site_grants_device_shape
    CHECK (device_id ~ '^[A-Za-z0-9-]{8,64}$'),
  CONSTRAINT extension_site_grants_label_length
    CHECK (char_length(device_label) <= 64)
);

-- One row per origin per browser. The conflict target for a push.
CREATE UNIQUE INDEX IF NOT EXISTS extension_site_grants_unique_idx
  ON public.extension_site_grants (user_id, device_id, origin);

CREATE INDEX IF NOT EXISTS extension_site_grants_user_idx
  ON public.extension_site_grants (user_id, device_label, origin);

-- ---------------------------------------------------------------------------
-- RLS and grants.
-- ---------------------------------------------------------------------------
ALTER TABLE public.extension_site_grants ENABLE ROW LEVEL SECURITY;

CREATE POLICY "extension_site_grants_select_own" ON public.extension_site_grants
  FOR SELECT TO authenticated USING (auth.uid() = user_id);

-- SELECT ONLY, and this one is load-bearing rather than stylistic: a direct
-- INSERT is exactly the widening path this design does not have. A client that
-- could write a row could add an origin the browser never granted, and the
-- extension's pull would then be a list of origins from the network.
--
-- NAME EVERY PRIVILEGE. Supabase's default privileges grant all of `arwdDxtm`
-- on a new table in `public` to anon, authenticated and service_role, and
-- TRUNCATE IS NOT FILTERED BY ROW SECURITY -- an authenticated role holding it
-- empties the table regardless of the policy above.
GRANT SELECT ON public.extension_site_grants TO authenticated;
REVOKE INSERT, UPDATE, DELETE, TRUNCATE, REFERENCES, TRIGGER
  ON public.extension_site_grants FROM authenticated;
REVOKE ALL ON public.extension_site_grants FROM anon;

-- ---------------------------------------------------------------------------
-- The extension's push. Replaces this device's list, and hands back what the
-- website has asked it to revoke.
-- ---------------------------------------------------------------------------
-- ONE CALL, NOT A PULL THEN A PUSH. The pending revocations are read inside the
-- same statement that rewrites the list, so a revocation made between a
-- separate read and write cannot be lost -- and a revoked origin that is still
-- in `p_input.origins` is deliberately NOT re-upserted, or the push would
-- resurrect the row it is about to be told to remove.
CREATE OR REPLACE FUNCTION public.sync_extension_site_grants(p_input jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  uid uuid := auth.uid();
  v_device text := p_input->>'device_id';
  v_label text := left(COALESCE(p_input->>'device_label', ''), 64);
  v_origins text[] := COALESCE(
    ARRAY(SELECT jsonb_array_elements_text(p_input->'origins')), ARRAY[]::text[]);
  v_revoke text[];
BEGIN
  IF uid IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'error', 'not_authenticated');
  END IF;
  IF v_device IS NULL OR v_device !~ '^[A-Za-z0-9-]{8,64}$' THEN
    RETURN jsonb_build_object('ok', false, 'error', 'invalid_device');
  END IF;

  -- What this browser is being asked to drop. Read first, and returned even
  -- when the origin is no longer in the pushed list -- the extension may have
  -- dropped it already, and saying so twice is harmless.
  SELECT COALESCE(array_agg(origin), ARRAY[]::text[]) INTO v_revoke
    FROM public.extension_site_grants
   WHERE user_id = uid AND device_id = v_device AND revoked_at IS NOT NULL;

  -- Gone from the browser, gone from here. This is what finally clears an
  -- applied revocation: the extension removes it locally and the next push no
  -- longer lists it.
  DELETE FROM public.extension_site_grants
   WHERE user_id = uid AND device_id = v_device
     AND NOT (origin = ANY (v_origins));

  INSERT INTO public.extension_site_grants
    (user_id, device_id, device_label, origin, last_seen_at)
  SELECT uid, v_device, v_label, o, now()
    FROM unnest(v_origins) AS o
   WHERE o ~ '^https?://[A-Za-z0-9._~-]+(:[0-9]{1,5})?$'
     AND NOT (o = ANY (v_revoke))
  ON CONFLICT (user_id, device_id, origin) DO UPDATE
    SET device_label = EXCLUDED.device_label,
        last_seen_at = now();

  RETURN jsonb_build_object('ok', true, 'revoke', to_jsonb(v_revoke));
EXCEPTION
  WHEN check_violation THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'rejected', 'detail', SQLERRM);
END;
$$;

-- ---------------------------------------------------------------------------
-- The website's revoke. Marks, never removes.
-- ---------------------------------------------------------------------------
-- Deleting the row here would be worse than useless: the extension's next push
-- would list the origin again, the row would come back, and the site would look
-- revoked for a second and then reappear with the grant still live in Chrome.
-- The mark is what survives until the browser has actually applied it.
CREATE OR REPLACE FUNCTION public.revoke_extension_site_grant(p_input jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  uid uuid := auth.uid();
  v_id uuid;
BEGIN
  IF uid IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'error', 'not_authenticated');
  END IF;
  BEGIN
    v_id := (p_input->>'id')::uuid;
  EXCEPTION WHEN invalid_text_representation THEN
    RETURN jsonb_build_object('ok', false, 'error', 'not_found');
  END;

  UPDATE public.extension_site_grants
     SET revoked_at = now()
   WHERE id = v_id AND user_id = uid AND revoked_at IS NULL;

  IF NOT FOUND THEN
    -- Already marked, or not theirs. Both answer the same way on purpose: a
    -- distinct "not yours" would tell a caller that someone else's row exists.
    RETURN jsonb_build_object('ok', true, 'already', true);
  END IF;
  RETURN jsonb_build_object('ok', true);
END;
$$;

-- ---------------------------------------------------------------------------
-- Grants, re-issued because CREATE OR REPLACE re-grants EXECUTE to PUBLIC.
-- ---------------------------------------------------------------------------
-- VERIFY BY READING `proacl` BACK after applying. Neither may list an empty
-- grantee:
--
--   SELECT p.proname, p.proacl FROM pg_proc p
--     JOIN pg_namespace n ON n.oid = p.pronamespace
--    WHERE n.nspname = 'public'
--      AND p.proname IN ('sync_extension_site_grants',
--                        'revoke_extension_site_grant');
REVOKE EXECUTE ON FUNCTION public.sync_extension_site_grants(jsonb) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.sync_extension_site_grants(jsonb) TO authenticated;

REVOKE EXECUTE ON FUNCTION public.revoke_extension_site_grant(jsonb) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.revoke_extension_site_grant(jsonb) TO authenticated;

COMMIT;
